import path from 'path';
import { processOutboxEnvelopes } from '../src/outbox-processor.js';

function printHelp() {
    console.log(`Process task dispatch outbox envelopes into queue outcomes

Usage:
  tsx scripts/process-outbox.ts [options]

Options:
  --store <path>               Queue store path (default: ../swarm-protocol/state/tasks.journal.jsonl)
  --outbox-dir <path>          Outbox directory path (default: ../swarm-protocol/state/outbox)
  --archive-dir <path>         Archive directory path (default: <outbox-dir>/processed)
  --from-agent <id>            Local orchestrator id for ingestion (default: agent:main)
  --eta-ms <n>                 Receipt ETA milliseconds (default: 1000)
  --result-delay-ms <n>        Result delay added to now for completedAt (default: 500)
  --failure-rate <0-1>         Failure injection probability (default: 0)
  --no-bot-runtime             Disable OpenClaw bot runtime execution and use simulation mode
  --bot-agent <id>             Bot agent id used for runtime execution (default: agent:openclaw-bot)
  --repo-root <path>           Repo root used to load skills/capabilities (default: ..)
  --skill-hardening <mode>     Skill hardening policy: off|report|enforce (default: enforce)
  --skill-min-score <n>        Minimum hardening score for deployability (default: 82)
  --deploy-index <path>        Optional skill deployability index JSON path
  --hardening-profile <path>   Optional skill hardening profile JSON path
  --no-enqueue-followups       Do not enqueue follow-up tasks generated by bot execution
  --dry-run                    Parse and plan without mutating store/outbox
  -h, --help                   Show help
`);
}

function parsePositiveInt(raw, flag) {
    const value = Number(raw);
    if (!Number.isInteger(value) || value < 0) {
        throw new Error(`${flag} must be a non-negative integer`);
    }
    return value;
}

function parseFailureRate(raw) {
    const value = Number(raw);
    if (!Number.isFinite(value) || value < 0 || value > 1) {
        throw new Error('--failure-rate must be between 0 and 1');
    }
    return value;
}

function parseHardeningPolicy(raw) {
    const value = String(raw || '').trim().toLowerCase();
    if (value !== 'off' && value !== 'report' && value !== 'enforce') {
        throw new Error('--skill-hardening must be one of: off, report, enforce');
    }
    return value;
}

function parseHardeningScore(raw) {
    const value = Number(raw);
    if (!Number.isFinite(value) || !Number.isInteger(value) || value < 1 || value > 100) {
        throw new Error('--skill-min-score must be an integer between 1 and 100');
    }
    return value;
}

function parseArgs(argv) {
    const defaultOutbox = path.resolve(process.cwd(), '../swarm-protocol/state/outbox');
    const options = {
        storePath: path.resolve(process.cwd(), '../swarm-protocol/state/tasks.journal.jsonl'),
        outboxDir: defaultOutbox,
        archiveDir: path.join(defaultOutbox, 'processed'),
        localAgentId: 'agent:main',
        etaMs: 1_000,
        resultDelayMs: 500,
        failureRate: 0,
        botRuntime: true,
        botAgentId: 'agent:openclaw-bot',
        botRepoRoot: path.resolve(process.cwd(), '..'),
        skillHardeningPolicy: 'enforce',
        skillHardeningMinScore: 82,
        skillDeployabilityIndexPath: null,
        skillHardeningProfilePath: null,
        enqueueFollowupTasks: true,
        dryRun: false,
        help: false
    };

    for (let i = 0; i < argv.length; i++) {
        const token = argv[i];

        if (token === '--help' || token === '-h') {
            options.help = true;
            continue;
        }
        if (token === '--dry-run') {
            options.dryRun = true;
            continue;
        }
        if (token === '--no-bot-runtime') {
            options.botRuntime = false;
            continue;
        }
        if (token === '--no-enqueue-followups') {
            options.enqueueFollowupTasks = false;
            continue;
        }

        const value = argv[i + 1];
        if (value === undefined) {
            throw new Error(`Missing value for ${token}`);
        }

        if (token === '--store') {
            options.storePath = path.resolve(process.cwd(), value);
            i++;
            continue;
        }
        if (token === '--outbox-dir') {
            options.outboxDir = path.resolve(process.cwd(), value);
            i++;
            continue;
        }
        if (token === '--archive-dir') {
            options.archiveDir = path.resolve(process.cwd(), value);
            i++;
            continue;
        }
        if (token === '--from-agent') {
            options.localAgentId = value;
            i++;
            continue;
        }
        if (token === '--eta-ms') {
            options.etaMs = parsePositiveInt(value, '--eta-ms');
            i++;
            continue;
        }
        if (token === '--result-delay-ms') {
            options.resultDelayMs = parsePositiveInt(value, '--result-delay-ms');
            i++;
            continue;
        }
        if (token === '--failure-rate') {
            options.failureRate = parseFailureRate(value);
            i++;
            continue;
        }
        if (token === '--bot-agent') {
            options.botAgentId = value;
            i++;
            continue;
        }
        if (token === '--repo-root') {
            options.botRepoRoot = path.resolve(process.cwd(), value);
            i++;
            continue;
        }
        if (token === '--skill-hardening') {
            options.skillHardeningPolicy = parseHardeningPolicy(value);
            i++;
            continue;
        }
        if (token === '--skill-min-score') {
            options.skillHardeningMinScore = parseHardeningScore(value);
            i++;
            continue;
        }
        if (token === '--deploy-index') {
            options.skillDeployabilityIndexPath = path.resolve(process.cwd(), value);
            i++;
            continue;
        }
        if (token === '--hardening-profile') {
            options.skillHardeningProfilePath = path.resolve(process.cwd(), value);
            i++;
            continue;
        }

        throw new Error(`Unknown argument: ${token}`);
    }

    if (!argv.includes('--archive-dir')) {
        options.archiveDir = path.join(options.outboxDir, 'processed');
    }

    return options;
}

function printSummary(stats) {
    console.log(`Loaded: ${stats.loaded}`);
    console.log(`Outbox files: ${stats.filesFound}`);
    console.log(`Archived files: ${stats.filesArchived}`);
    console.log(`Envelopes seen: ${stats.envelopesSeen}`);
    console.log(`Envelopes invalid: ${stats.envelopesInvalid}`);
    console.log(`Receipts accepted: ${stats.receiptsAccepted}`);
    console.log(`Results accepted: ${stats.resultsAccepted}`);
    console.log(`Skipped unknown tasks: ${stats.skippedUnknownTask}`);
    console.log(`Skipped terminal tasks: ${stats.skippedTerminal}`);
    if (stats.botRuntime) {
        console.log(`Bot tasks executed: ${stats.botTasksExecuted}`);
        console.log(`Bot failures: ${stats.botTasksFailed}`);
        console.log(`Bot skill tasks: ${stats.botSkillTasks}`);
        console.log(`Bot skill hardening blocked: ${stats.botSkillHardeningBlocked}`);
        console.log(`Bot skill action tasks: ${stats.botSkillActionTasks}`);
        console.log(`Bot skill blueprint tasks: ${stats.botSkillBlueprintTasks}`);
        console.log(`Bot capability tasks: ${stats.botCapabilityTasks}`);
        console.log(`Bot capability action tasks: ${stats.botCapabilityActionTasks}`);
        console.log(`Bot generic tasks: ${stats.botGenericTasks}`);
        console.log(`Follow-up tasks generated: ${stats.followupTasksGenerated}`);
        console.log(`Follow-up tasks accepted: ${stats.followupTasksAccepted}`);
        console.log(`Follow-up tasks saved: ${stats.followupTasksSaved}`);
        console.log(`Follow-up tasks skipped: ${stats.followupTasksSkipped}`);
    }
    if (stats.dryRun) {
        console.log('Dry run: no changes applied.');
    }
}

(async () => {
    try {
        const options = parseArgs(process.argv.slice(2));
        if (options.help) {
            printHelp();
            return;
        }

        const stats = await processOutboxEnvelopes({
            storePath: options.storePath,
            outboxDir: options.outboxDir,
            archiveDir: options.archiveDir,
            localAgentId: options.localAgentId,
            etaMs: options.etaMs,
            resultDelayMs: options.resultDelayMs,
            failureRate: options.failureRate,
            botRuntime: options.botRuntime,
            botAgentId: options.botAgentId,
            botRepoRoot: options.botRepoRoot,
            skillHardeningPolicy: options.skillHardeningPolicy,
            skillHardeningMinScore: options.skillHardeningMinScore,
            skillDeployabilityIndexPath: options.skillDeployabilityIndexPath,
            skillHardeningProfilePath: options.skillHardeningProfilePath,
            enqueueFollowupTasks: options.enqueueFollowupTasks,
            dryRun: options.dryRun
        });
        printSummary(stats);
    } catch (error) {
        console.error(`process-outbox failed: ${error.message}`);
        process.exit(1);
    }
})();
